export function humanizeCode(value: string): string {
  return value
    .replaceAll("_", " ")
    .replaceAll("-", " ")
    .replace(/\b\w/g, (match) => match.toUpperCase());
}

export function t(
  locale: SupportedLocale,
  key: UiMessageKey,
  values: Record<string, string | number> = {},
): string {
  const template = uiMessages[locale]?.[key] ?? englishUiMessages[key];
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => {
    const value = values[name];
    return value == null ? `{${name}}` : String(value);
  });
}

export function localeName(
  value: SupportedLocale,
  displayLocale: SupportedLocale = defaultLocale,
): string {
  return localeNames[displayLocale]?.[value] ?? localeNativeNames[value];
}

export function facetLabel<Group extends FacetGroup>(
  locale: SupportedLocale,
  group: Group,
  value: string,
): string {
  const labels = facetMessages[locale][group] as Record<string, string>;
  const englishLabels = englishFacetMessages[group] as Record<string, string>;
  return labels[value] ?? englishLabels[value] ?? humanizeCode(value);
}

export function formatDateTime(value: string | null, locale: SupportedLocale): string | null {
  if (!value) {
    return null;
  }

  const date = new Date(value);
  if (Number.isNaN(date.getTime())) {
    return value;
  }

  return new Intl.DateTimeFormat(locale, {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(date);
}

export function formatNumber(value: number, locale: SupportedLocale): string {
  return new Intl.NumberFormat(locale).format(value);
}
